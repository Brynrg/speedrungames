#!/usr/bin/env node
// Generates apps/web/public/_redirects from src/lib/games.data.json.
//
// For every game with a `proxyTo` field, emits two lines:
//   /games/<slug>      /games/<slug>/      301
//   /games/<slug>/*    <proxyTo>/:splat    200!
//
// The 301 normalizes bare URLs to trailing-slash form so the splat matches.
// The 200! force-proxies past any Next route at the same path.
//
// Run by the `prebuild` script before `next build`.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const DATA = resolve(ROOT, "src/lib/games.data.json");
const OUT = resolve(ROOT, "public/_redirects");

const games = JSON.parse(readFileSync(DATA, "utf8"));

const proxied = games.filter((g) => typeof g.proxyTo === "string" && g.proxyTo.length > 0);

const lines = [
  "# AUTO-GENERATED by apps/web/scripts/generate-redirects.mjs",
  "# Source: apps/web/src/lib/games.data.json",
  "# Do not edit by hand — re-run `pnpm -C apps/web build` (or prebuild) to regenerate.",
  "",
];

for (const game of proxied) {
  const target = game.proxyTo.replace(/\/+$/, "");
  lines.push(`# ${game.slug}`);
  lines.push(`/games/${game.slug}        /games/${game.slug}/        301`);
  lines.push(`/games/${game.slug}/*      ${target}/:splat            200!`);
  lines.push("");
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n"), "utf8");

console.log(
  `generate-redirects: wrote ${proxied.length} proxy rule${proxied.length === 1 ? "" : "s"} to ${OUT.replace(ROOT + "/", "")}`,
);
